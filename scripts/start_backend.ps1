# ReceiptLedger - Background Service Runner & Sleep-Recovery Watchdog
param(
    [switch]$Watchdog = $false
)

$ErrorActionPreference = "SilentlyContinue"
$ScriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$ProjectRoot = Split-Path -Parent $ScriptDir
$BackendDir = Join-Path $ProjectRoot "backend"
$LogPath = Join-Path $ScriptDir "tunnel.log"
$UrlFile = Join-Path $ScriptDir "current_tunnel_url.txt"
$MobileEnv = Join-Path $ProjectRoot "mobile\.env"
$LtLog = Join-Path $ScriptDir "localtunnel.log"

# Candidate cloudflared binary paths
$CloudflaredPath = "C:\Program Files (x86)\cloudflared\cloudflared.exe"
if (-not (Test-Path $CloudflaredPath)) {
    $alt = "C:\Program Files\cloudflared\cloudflared.exe"
    if (Test-Path $alt) { $CloudflaredPath = $alt }
    else {
        $cmdPath = (Get-Command cloudflared -ErrorAction SilentlyContinue).Source
        if ($cmdPath) { $CloudflaredPath = $cmdPath }
    }
}

# 1. Detect Real Physical Wi-Fi IPv4 Address via active route
$localIp = "127.0.0.1"
try {
    $route = Find-NetRoute -RemoteIPAddress '8.8.8.8' -ErrorAction SilentlyContinue | Select-Object -First 1
    if ($route -and $route.IPAddress) {
        $localIp = $route.IPAddress
    }
} catch {
    try {
        $ips = Get-NetIPAddress -AddressFamily IPv4 -ErrorAction SilentlyContinue | Where-Object {
            $_.InterfaceAlias -notmatch 'Loopback|vEthernet|WSL|Virtual|Bluetooth' -and
            $_.IPAddress -notmatch '^169\.254\.' -and
            $_.IPAddress -notmatch '^127\.'
        }
        if ($ips) {
            $preferred = $ips | Where-Object { $_.IPAddress -match '^(192\.168\.|10\.)' } | Select-Object -First 1
            if ($preferred) { $localIp = $preferred.IPAddress } else { $localIp = $ips[0].IPAddress }
        }
    } catch {}
}

function Sync-Config($activeUrl) {
    if ($activeUrl) {
        Set-Content -Path $UrlFile -Value $activeUrl -Force
        $envContent = @"
# Generated by ReceiptLedger Service Launcher
API_BASE_URL=$activeUrl
API_TIMEOUT_SECONDS=45
DEBUG=false
"@
        Set-Content -Path $MobileEnv -Value $envContent -Force
    }
}

function Start-BackendServer {
    $backendAlive = $false
    try {
        $r = Invoke-RestMethod -Uri "http://127.0.0.1:8000/api/v1/health" -TimeoutSec 2 -ErrorAction Stop
        if ($r.status -eq "ok") { $backendAlive = $true }
    } catch {
        $backendAlive = $false
    }

    if (-not $backendAlive) {
        # Terminate any dead or stuck uvicorn process
        Get-Process python -ErrorAction SilentlyContinue | Where-Object { $_.CommandLine -match "app.main:app" } | Stop-Process -Force -ErrorAction SilentlyContinue
        Start-Sleep -Milliseconds 500

        # Launch Uvicorn bound to 0.0.0.0 so both local loopback and Wi-Fi LAN devices connect
        Start-Process -FilePath "python" -ArgumentList "-m uvicorn app.main:app --host 0.0.0.0 --port 8000" -WorkingDirectory $BackendDir -WindowStyle Hidden
        
        # Poll up to 10 seconds for backend initialization
        for ($k = 0; $k -lt 10; $k++) {
            Start-Sleep -Seconds 1
            try {
                $r = Invoke-RestMethod -Uri "http://127.0.0.1:8000/api/v1/health" -TimeoutSec 2 -ErrorAction Stop
                if ($r.status -eq "ok") { break }
            } catch {}
        }
    }
}

function Ensure-Tunnel {
    # 1. Verify existing tunnel health
    if (Test-Path $UrlFile) {
        $existingUrl = (Get-Content $UrlFile -Raw).Trim()
        if ($existingUrl) {
            try {
                $resp = Invoke-RestMethod -Uri "$existingUrl/api/v1/health" -TimeoutSec 3 -ErrorAction Stop
                if ($resp.status -eq "ok") {
                    Sync-Config $existingUrl
                    return $existingUrl
                }
            } catch {}
        }
    }

    # 2. Check if local ISP DNS resolves trycloudflare.com
    $canResolveCloudflare = $false
    try {
        $dns = Resolve-DnsName -Name "trycloudflare.com" -ErrorAction Stop
        if ($dns) { $canResolveCloudflare = $true }
    } catch {
        $canResolveCloudflare = $false
    }

    $foundUrl = $null

    # Priority A: Cloudflare Quick Tunnel (if DNS resolver permits)
    if ($canResolveCloudflare -and (Test-Path $CloudflaredPath)) {
        Get-Process cloudflared -ErrorAction SilentlyContinue | Stop-Process -Force -ErrorAction SilentlyContinue
        Start-Sleep -Milliseconds 300
        if (Test-Path $LogPath) { Remove-Item $LogPath -Force }

        Start-Process -FilePath $CloudflaredPath -ArgumentList "tunnel --edge-ip-version 4 --url http://127.0.0.1:8000" -RedirectStandardError $LogPath -WindowStyle Hidden
        
        for ($i = 0; $i -lt 10; $i++) {
            Start-Sleep -Seconds 1
            if (Test-Path $LogPath) {
                $content = Get-Content $LogPath -Raw -ErrorAction SilentlyContinue
                if ($content -match "failed to request quick Tunnel" -or $content -match "context deadline exceeded") {
                    break
                }
                if ($content -match "https://[a-zA-Z0-9\-]+\.trycloudflare\.com") {
                    $foundUrl = $Matches[0]
                    break
                }
            }
        }
    }

    # Priority B: Localtunnel via npx (loca.lt) - bypasses regional ISP DNS filtering
    if (-not $foundUrl) {
        $npxBin = (Get-Command npx.cmd -ErrorAction SilentlyContinue).Source
        if (-not $npxBin) { $npxBin = (Get-Command npx -ErrorAction SilentlyContinue).Source }
        
        if ($npxBin) {
            if (Test-Path $LtLog) { Remove-Item $LtLog -Force }
            Start-Process -FilePath "cmd.exe" -ArgumentList "/c npx -y localtunnel --port 8000 > `"$LtLog`" 2>&1" -WindowStyle Hidden
            
            for ($j = 0; $j -lt 8; $j++) {
                Start-Sleep -Seconds 1
                if (Test-Path $LtLog) {
                    $ltContent = Get-Content $LtLog -Raw -ErrorAction SilentlyContinue
                    if ($ltContent -match "https://[a-zA-Z0-9\-]+\.loca\.lt") {
                        $foundUrl = $Matches[0]
                        break
                    }
                }
            }
        }
    }

    # Priority C: High-performance direct LAN Wi-Fi connection
    if (-not $foundUrl) {
        $foundUrl = "http://${localIp}:8000"
    }

    Sync-Config $foundUrl
    return $foundUrl
}

# --- Execution ---
Write-Host "======================================================================" -ForegroundColor DarkGreen
Write-Host "       ReceiptLedger Backend & Edge Tunnel Controller" -ForegroundColor Green
Write-Host "======================================================================" -ForegroundColor DarkGreen

Start-BackendServer
$activeUrl = Ensure-Tunnel

# Query health status
$healthStatus = "Starting..."
$geminiStatus = "Ready"
$dbStatus = "Supabase"
try {
    $h = Invoke-RestMethod -Uri "http://127.0.0.1:8000/api/v1/health" -TimeoutSec 3 -ErrorAction Stop
    $healthStatus = $h.status
    if ($h.engines.gemini) { $geminiStatus = $h.engines.gemini }
    if ($h.engines.database) { $dbStatus = $h.engines.database }
} catch {}

Write-Host " [+] Local Loopback:   " -NoNewline; Write-Host "http://127.0.0.1:8000" -ForegroundColor Cyan
Write-Host " [+] Local Wi-Fi LAN:  " -NoNewline; Write-Host "http://${localIp}:8000" -ForegroundColor Cyan
Write-Host " [+] Interactive Docs: " -NoNewline; Write-Host "http://127.0.0.1:8000/docs" -ForegroundColor Gray
Write-Host " [+] Active URL:       " -NoNewline; Write-Host $activeUrl -ForegroundColor Green
Write-Host " [+] Synced Config:    " -NoNewline; Write-Host "mobile\.env (API_BASE_URL=$activeUrl)" -ForegroundColor DarkYellow
Write-Host " [+] Engines:          " -NoNewline; Write-Host "Gemini=$geminiStatus | DB=$dbStatus" -ForegroundColor Magenta
Write-Host "======================================================================" -ForegroundColor DarkGreen

if ($Watchdog) {
    Write-Host "[*] Sleep-Recovery Watchdog active. Polling every 15 seconds..." -ForegroundColor Gray
    while ($true) {
        Start-Sleep -Seconds 15
        Start-BackendServer
        Ensure-Tunnel | Out-Null
    }
}
