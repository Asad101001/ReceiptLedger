import os
import sys
import time
import shutil
import urllib.request
import subprocess
import threading
import re
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
BACKEND_DIR = REPO_ROOT / "backend"
MOBILE_ENV = REPO_ROOT / "mobile" / ".env"
BIN_DIR = REPO_ROOT / "scripts" / "devops" / "bin"
CLOUDFLARED_EXE = BIN_DIR / "cloudflared.exe"

CLOUDFLARED_URL = (
    "https://github.com/cloudflare/cloudflared/releases/latest/download/cloudflared-windows-amd64.exe"
)


def ensure_cloudflared() -> str | None:
    """Finds or downloads portable cloudflared executable."""
    # Check if cloudflared is already in PATH
    path_bin = shutil.which("cloudflared")
    if path_bin:
        return path_bin

    if CLOUDFLARED_EXE.is_file():
        return str(CLOUDFLARED_EXE)

    print("[*] Cloudflare Tunnel binary not detected locally.")
    print("    Downloading portable single-file cloudflared.exe (zero-install)...")
    BIN_DIR.mkdir(parents=True, exist_ok=True)
    try:
        urllib.request.urlretrieve(CLOUDFLARED_URL, CLOUDFLARED_EXE)
        print("    [+] cloudflared.exe downloaded successfully!")
        return str(CLOUDFLARED_EXE)
    except Exception as e:
        print(f"    [-] Automatic download failed: {e}")
        print("    [!] Falling back to native OpenSSH Pinggy tunnel.")
        return None


def update_mobile_env(public_url: str):
    """Updates mobile/.env with the active tunnel URL."""
    if not MOBILE_ENV.parent.exists():
        return

    content = f"# Generated by ReceiptLedger Tunnel Launcher\nAPI_BASE_URL={public_url}\nAPI_TIMEOUT_SECONDS=45\nDEBUG=false\n"
    try:
        MOBILE_ENV.write_text(content, encoding="utf-8")
        print(f"    [+] Automatically updated mobile/.env -> API_BASE_URL={public_url}")
    except Exception as e:
        print(f"    [-] Could not write to mobile/.env: {e}")


def run_backend_process():
    """Starts FastAPI uvicorn server in backend directory."""
    print("[1/2] Starting FastAPI backend on http://127.0.0.1:8000 ...")
    python_exe = sys.executable

    # Check for venv python
    venv_py = BACKEND_DIR / ".venv" / "Scripts" / "python.exe"
    if venv_py.is_file():
        python_exe = str(venv_py)

    env = os.environ.copy()
    env["PYTHONPATH"] = str(BACKEND_DIR)

    proc = subprocess.Popen(
        [python_exe, "-m", "uvicorn", "app.main:app", "--host", "127.0.0.1", "--port", "8000"],
        cwd=str(BACKEND_DIR),
        env=env,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )
    return proc


import socket


def get_local_ip() -> str:
    """Detects local LAN IPv4 address for direct Wi-Fi connections."""
    try:
        s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        s.connect(("8.8.8.8", 80))
        ip = s.getsockname()[0]
        s.close()
        return ip
    except Exception:
        return "127.0.0.1"


def start_localtunnel():
    """Runs localtunnel via npx with zero configuration."""
    npx_bin = shutil.which("npx") or "npx"
    print("[2/2] Launching Localtunnel (100% Free, Zero Card, Instant HTTPS)...")
    cmd = [npx_bin, "--yes", "localtunnel", "--port", "8000"]

    proc = subprocess.Popen(
        cmd,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        bufsize=1,
        shell=True,
    )

    url_found = None
    url_pattern = re.compile(r"https://[a-zA-Z0-9-]+\.loca\.lt")

    start_time = time.time()
    for line in proc.stdout:
        match = url_pattern.search(line)
        if match:
            url_found = match.group(0)
            break
        if time.time() - start_time > 12:
            break

    return proc, url_found


def start_cloudflare_tunnel(bin_path: str):
    """Runs cloudflared tunnel with safe timeout and error detection."""
    print("[2/2] Launching Cloudflare Tunnel (100% Free, Zero Card)...")
    print("      Connecting to Cloudflare global edge network...")
    cmd = [bin_path, "tunnel", "--url", "http://127.0.0.1:8000"]

    proc = subprocess.Popen(
        cmd,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        bufsize=1,
    )

    url_found = None
    url_pattern = re.compile(r"https://([a-zA-Z0-9-]+)\.trycloudflare\.com")

    start_time = time.time()
    # Read with non-blocking check or line-by-line with strict timeout
    while time.time() - start_time < 12:
        line = proc.stdout.readline()
        if not line:
            if proc.poll() is not None:
                break
            time.sleep(0.2)
            continue

        if "failed to request quick Tunnel" in line or "context deadline exceeded" in line:
            print("      [!] Cloudflare edge timed out from your ISP network.")
            break

        match = url_pattern.search(line)
        if match:
            subdomain = match.group(1).lower()
            if subdomain not in ("api", "www", "developers", "blog"):
                url_found = match.group(0)
                break

    if not url_found:
        proc.terminate()

    return proc, url_found


def start_pinggy_ssh_tunnel():
    """Runs pinggy fallback via native Windows OpenSSH."""
    print("[2/2] Launching Pinggy SSH Tunnel (Zero Install, Native OpenSSH)...")
    ssh_bin = shutil.which("ssh") or "ssh"
    cmd = [
        ssh_bin,
        "-p", "443",
        "-R", "0:127.0.0.1:8000",
        "-o", "StrictHostKeyChecking=no",
        "-o", "ServerAliveInterval=30",
        "a.pinggy.io",
    ]

    proc = subprocess.Popen(
        cmd,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        bufsize=1,
    )

    url_found = None
    url_pattern = re.compile(r"https://[a-zA-Z0-9-]+\.a\.pinggy\.link")

    start_time = time.time()
    for line in proc.stdout:
        match = url_pattern.search(line)
        if match:
            url_found = match.group(0)
            break
        if time.time() - start_time > 10:
            break

    return proc, url_found


def main():
    print("=" * 70)
    print(" ReceiptLedger Zero-Cost HTTPS Tunnel & Backend")
    print(" Cost: $0.00 / mo | No Credit Card | No Cloud Accounts Required")
    print("=" * 70)

    # 1. Start FastAPI backend
    backend_proc = run_backend_process()
    time.sleep(2)

    local_ip = get_local_ip()
    tunnel_proc = None
    public_url = None

    # Priority 1: Cloudflare Tunnel (fast global edge, if reachable)
    cf_bin = ensure_cloudflared()
    if cf_bin:
        tunnel_proc, public_url = start_cloudflare_tunnel(cf_bin)

    # Priority 2: Localtunnel (blazing fast, unblocked fallback via Node/npx)
    if not public_url and shutil.which("npx"):
        print("[*] Switching to Localtunnel fallback...")
        tunnel_proc, public_url = start_localtunnel()

    # Priority 3: Pinggy SSH Tunnel
    if not public_url:
        print("[*] Switching to Pinggy SSH fallback...")
        tunnel_proc, public_url = start_pinggy_ssh_tunnel()

    if public_url:
        print("\n" + "=" * 70)
        print(f" SUCCESS: BACKEND IS LIVE & SECURELY TUNNELED!")
        print(f" Public HTTPS URL:  {public_url}")
        print(f" Local Wi-Fi URL:   http://{local_ip}:8000")
        print(f" Interactive Docs:  {public_url}/docs")
        print(f" Health Check:      {public_url}/api/v1/health")
        print("=" * 70 + "\n")

        update_mobile_env(public_url)
        print("[*] Leave this terminal open to keep your backend live.")
        print("[*] Press Ctrl+C at any time to shut down the backend and tunnel.")
    else:
        print("\n[-] Error: Could not establish public HTTPS tunnel.")
        print("    Local backend is still running at http://127.0.0.1:8000")

    try:
        while True:
            time.sleep(1)
    except KeyboardInterrupt:
        print("\n[*] Shutting down tunnel and backend gracefully...")
        if tunnel_proc:
            tunnel_proc.terminate()
        if backend_proc:
            backend_proc.terminate()
        print("[+] Done. Goodbye!")


if __name__ == "__main__":
    main()
