import os
import sys
import time
import shutil
import urllib.request
import subprocess
import threading
import re
import json
import socket
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
BACKEND_DIR = REPO_ROOT / "backend"
MOBILE_ENV = REPO_ROOT / "mobile" / ".env"
URL_FILE = REPO_ROOT / "scripts" / "current_tunnel_url.txt"
WEB_ENV_LOCAL = REPO_ROOT / "web" / ".env.local"
BIN_DIR = REPO_ROOT / "scripts" / "devops" / "bin"
CLOUDFLARED_EXE = BIN_DIR / "cloudflared.exe"

STATIC_DOMAIN = "disagree-slick-record.ngrok-free.dev"
STATIC_HTTPS_URL = f"https://{STATIC_DOMAIN}"

CLOUDFLARED_URL = (
    "https://github.com/cloudflare/cloudflared/releases/latest/download/cloudflared-windows-amd64.exe"
)


def find_ngrok_bin() -> str | None:
    """Finds ngrok executable on PATH or in local venvs/appdata."""
    candidates = [
        shutil.which("ngrok"),
        shutil.which("ngrok.exe"),
        str(BACKEND_DIR / ".venv" / "Scripts" / "ngrok.exe"),
        str(REPO_ROOT / ".venv" / "Scripts" / "ngrok.exe"),
        r"C:\Users\Asad\AppData\Local\ngrok\ngrok.exe",
        r"C:\Program Files\ngrok\ngrok.exe",
        r"C:\Program Files (x86)\ngrok\ngrok.exe",
    ]
    for c in candidates:
        if c and Path(c).is_file():
            return str(Path(c).resolve())
    return None


def terminate_stale_ngrok():
    """Terminates any dead or lingering ngrok processes."""
    if os.name == "nt":
        subprocess.run(["taskkill", "/F", "/IM", "ngrok.exe"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        time.sleep(0.5)


def ensure_cloudflared() -> str | None:
    """Finds or downloads portable cloudflared executable."""
    path_bin = shutil.which("cloudflared")
    if path_bin:
        return path_bin

    if CLOUDFLARED_EXE.is_file():
        return str(CLOUDFLARED_EXE)

    print("[*] Cloudflare Tunnel binary not detected locally.")
    print("    Downloading portable single-file cloudflared.exe (zero-install)...")
    BIN_DIR.mkdir(parents=True, exist_ok=True)
    try:
        urllib.request.urlretrieve(CLOUDFLARED_URL, CLOUDFLARED_EXE)
        print("    [+] cloudflared.exe downloaded successfully!")
        return str(CLOUDFLARED_EXE)
    except Exception as e:
        print(f"    [-] Automatic download failed: {e}")
        return None


def sync_all_configs(public_url: str):
    """Synchronizes active public tunnel URL across mobile/.env, current_tunnel_url.txt, and web/.env.local."""
    clean_url = public_url.strip().replace("/api/v1", "").rstrip("/")
    
    # 1. scripts/current_tunnel_url.txt
    try:
        URL_FILE.parent.mkdir(parents=True, exist_ok=True)
        URL_FILE.write_text(clean_url, encoding="utf-8")
        print(f"    [+] Updated {URL_FILE.name} -> {clean_url}")
    except Exception as e:
        print(f"    [-] Could not write to {URL_FILE.name}: {e}")

    # 2. mobile/.env
    if MOBILE_ENV.parent.exists():
        content = f"# Generated by ReceiptLedger Tunnel Launcher\nAPI_BASE_URL={clean_url}\nAPI_TIMEOUT_SECONDS=45\nDEBUG=false\n"
        try:
            MOBILE_ENV.write_text(content, encoding="utf-8")
            print(f"    [+] Updated mobile/.env -> API_BASE_URL={clean_url}")
        except Exception as e:
            print(f"    [-] Could not write to mobile/.env: {e}")

    # 3. web/.env.local (keeps local web dev pointed to public tunnel if desired)
    try:
        lines = []
        if WEB_ENV_LOCAL.is_file():
            for line in WEB_ENV_LOCAL.read_text(encoding="utf-8").splitlines():
                if not line.startswith("VITE_API_BASE_URL="):
                    lines.append(line)
        lines.append(f"VITE_API_BASE_URL={clean_url}/api/v1")
        WEB_ENV_LOCAL.write_text("\n".join(lines) + "\n", encoding="utf-8")
    except Exception:
        pass


def is_backend_running(port: int = 8000) -> bool:
    """Checks if a backend server is already listening on the target port."""
    try:
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
            s.settimeout(1.0)
            return s.connect_ex(("127.0.0.1", port)) == 0
    except Exception:
        return False


def run_backend_process():
    """Starts FastAPI uvicorn server in backend directory if not already running."""
    if is_backend_running(8000):
        print("[1/2] FastAPI backend is already active on http://127.0.0.1:8000 (reusing running instance)")
        return None

    print("[1/2] Starting FastAPI backend on http://127.0.0.1:8000 ...")
    python_exe = sys.executable

    # Check for venv python
    venv_py = BACKEND_DIR / ".venv" / "Scripts" / "python.exe"
    if venv_py.is_file():
        python_exe = str(venv_py)

    env = os.environ.copy()
    env["PYTHONPATH"] = str(BACKEND_DIR)

    tess_path = Path(r"C:\Program Files\Tesseract-OCR")
    if (tess_path / "tesseract.exe").is_file():
        env["PATH"] = f"{tess_path};{env.get('PATH', '')}"
        env["TESSDATA_PREFIX"] = str(tess_path / "tessdata")

    proc = subprocess.Popen(
        [python_exe, "-m", "uvicorn", "app.main:app", "--host", "0.0.0.0", "--port", "8000", "--reload"],
        cwd=str(BACKEND_DIR),
        env=env,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )
    # Wait for startup
    for _ in range(10):
        time.sleep(0.5)
        if is_backend_running(8000):
            break
    return proc


def get_local_ip() -> str:
    """Detects local LAN IPv4 address for direct Wi-Fi connections."""
    try:
        s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        s.connect(("8.8.8.8", 80))
        ip = s.getsockname()[0]
        s.close()
        return ip
    except Exception:
        return "127.0.0.1"


def is_ngrok_online() -> bool:
    """Checks if the local ngrok client agent and tunnel endpoint are alive."""
    # 1. Local ngrok inspection API
    try:
        req = urllib.request.Request("http://127.0.0.1:4040/api/tunnels")
        with urllib.request.urlopen(req, timeout=2) as resp:
            data = json.loads(resp.read().decode("utf-8"))
            for t in data.get("tunnels", []):
                pub = t.get("public_url", "")
                if STATIC_DOMAIN in pub:
                    return True
    except Exception:
        pass

    # 2. Direct public health ping
    try:
        req = urllib.request.Request(f"{STATIC_HTTPS_URL}/api/v1/health")
        with urllib.request.urlopen(req, timeout=3) as resp:
            return resp.status == 200
    except Exception:
        pass

    return False


def start_ngrok_tunnel(ngrok_bin: str):
    """Runs ngrok tunnel bound to the permanent static domain."""
    print(f"[2/2] Launching Ngrok Tunnel with permanent static domain...")
    print(f"      Domain: {STATIC_HTTPS_URL}")
    terminate_stale_ngrok()

    cmd = [ngrok_bin, "http", "8000", "--url", STATIC_HTTPS_URL]
    proc = subprocess.Popen(
        cmd,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )

    # Wait for tunnel initialization
    for i in range(8):
        time.sleep(0.75)
        if is_ngrok_online():
            print("      [+] Tunnel established successfully via Ngrok Cloud Edge!")
            return proc, STATIC_HTTPS_URL

    # Check inspection API for any assigned public URL
    try:
        req = urllib.request.Request("http://127.0.0.1:4040/api/tunnels")
        with urllib.request.urlopen(req, timeout=2) as resp:
            data = json.loads(resp.read().decode("utf-8"))
            for t in data.get("tunnels", []):
                if t.get("public_url"):
                    return proc, t["public_url"]
    except Exception:
        pass

    return proc, STATIC_HTTPS_URL


def start_cloudflare_tunnel(bin_path: str):
    """Runs cloudflared tunnel with safe timeout and error detection."""
    print("[2/2] Launching Cloudflare Tunnel (100% Free, Zero Card)...")
    cmd = [bin_path, "tunnel", "--url", "http://127.0.0.1:8000"]
    proc = subprocess.Popen(
        cmd,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        bufsize=1,
    )

    url_found = None
    url_pattern = re.compile(r"https://([a-zA-Z0-9-]+)\.trycloudflare\.com")
    start_time = time.time()
    while time.time() - start_time < 12:
        line = proc.stdout.readline()
        if not line:
            if proc.poll() is not None:
                break
            time.sleep(0.2)
            continue
        if "failed to request quick Tunnel" in line or "context deadline exceeded" in line:
            break
        match = url_pattern.search(line)
        if match:
            subdomain = match.group(1).lower()
            if subdomain not in ("api", "www", "developers", "blog"):
                url_found = match.group(0)
                break

    if not url_found:
        proc.terminate()
    return proc, url_found


def start_localtunnel():
    """Runs localtunnel via npx with zero configuration."""
    npx_bin = shutil.which("npx") or "npx"
    print("[2/2] Launching Localtunnel fallback (100% Free, Zero Card)...")
    cmd = [npx_bin, "--yes", "localtunnel", "--port", "8000"]
    proc = subprocess.Popen(
        cmd,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        bufsize=1,
        shell=True,
    )
    url_found = None
    url_pattern = re.compile(r"https://[a-zA-Z0-9-]+\.loca\.lt")
    start_time = time.time()
    for line in proc.stdout:
        match = url_pattern.search(line)
        if match:
            url_found = match.group(0)
            break
        if time.time() - start_time > 12:
            break
    return proc, url_found


def main():
    print("=" * 72)
    print(" ReceiptLedger HTTPS Tunnel & Permanent Static Gateway")
    print(f" Permanent Static Domain: {STATIC_HTTPS_URL}")
    print("=" * 72)

    # 1. Start or verify FastAPI backend
    backend_proc = run_backend_process()
    time.sleep(1)

    local_ip = get_local_ip()
    tunnel_proc = None
    public_url = None

    # Priority 1: Ngrok Permanent Static Domain (Guarantees Static Domain)
    ngrok_bin = find_ngrok_bin()
    if ngrok_bin:
        tunnel_proc, public_url = start_ngrok_tunnel(ngrok_bin)

    # Priority 2: Cloudflare Tunnel (if ngrok not available)
    if not public_url:
        cf_bin = ensure_cloudflared()
        if cf_bin:
            tunnel_proc, public_url = start_cloudflare_tunnel(cf_bin)

    # Priority 3: Localtunnel
    if not public_url and shutil.which("npx"):
        tunnel_proc, public_url = start_localtunnel()

    # Priority 4: LAN Wi-Fi
    if not public_url:
        public_url = f"http://{local_ip}:8000"

    sync_all_configs(public_url)

    print("\n" + "=" * 72)
    print(" SUCCESS: BACKEND IS LIVE & SECURELY TUNNELED!")
    print(f" Permanent Public HTTPS URL: {public_url}")
    print(f" Vercel Dashboard Gateway:   {public_url}/api/v1")
    print(f" Local Loopback:             http://127.0.0.1:8000")
    print(f" Local Wi-Fi LAN:            http://{local_ip}:8000")
    print(f" Interactive Swagger Docs:   {public_url}/docs")
    print(f" Health Check Endpoint:      {public_url}/api/v1/health")
    print("=" * 72)
    print("[*] Leave this terminal window running in the background.")
    print("[*] Sleep-Recovery & Keep-Alive Watchdog active (polling every 10s)...")
    print("[*] Press Ctrl+C at any time to shut down.\n")

    # Keep-Alive Watchdog loop
    try:
        while True:
            time.sleep(10)
            # 1. Check if backend died
            if not is_backend_running(8000):
                print("[!] Local backend died. Restarting uvicorn...")
                backend_proc = run_backend_process()

            # 2. Check if ngrok died or tunnel dropped
            if ngrok_bin and not is_ngrok_online():
                print("[!] Static Ngrok tunnel dropped. Re-establishing permanent domain...")
                if tunnel_proc:
                    try:
                        tunnel_proc.terminate()
                    except Exception:
                        pass
                tunnel_proc, public_url = start_ngrok_tunnel(ngrok_bin)
                sync_all_configs(public_url)
    except KeyboardInterrupt:
        print("\n[*] Shutting down tunnel and backend gracefully...")
        if tunnel_proc:
            try:
                tunnel_proc.terminate()
            except Exception:
                pass
        terminate_stale_ngrok()
        if backend_proc:
            try:
                backend_proc.terminate()
            except Exception:
                pass
        print("[+] All services stopped cleanly. Goodbye!")


if __name__ == "__main__":
    main()
